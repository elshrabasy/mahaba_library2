import assert from 'node:assert/strict';
import fs from 'node:fs';
import {generateMahabatNative} from '../engine/registry.js';

const html=fs.readFileSync(new URL('../pilot/studio-v2.html',import.meta.url),'utf8');
const js=fs.readFileSync(new URL('../pilot/studio-v2.js',import.meta.url),'utf8');
const nest=fs.readFileSync(new URL('../assets/studio/nesting.html',import.meta.url),'utf8');
const shared=fs.readFileSync(new URL('../studio-src/shared-studio.js',import.meta.url),'utf8');
const adapter=fs.readFileSync(new URL('../studio-src/mahabat-shared-studio.js',import.meta.url),'utf8');
const productionLink=fs.readFileSync(new URL('../studio-src/production-link.js',import.meta.url),'utf8');
const engineeringPanel=fs.readFileSync(new URL('../studio-src/engineering-panel.js',import.meta.url),'utf8');

assert.match(html,/assets\/studio\/gallery-theme\.css/,'Studio must use first-library theme');
assert.match(js,/MahabatSharedStudio/,'Viewer must keep SharedStudio and only adapt source');
assert.doesNotMatch(js,/paperTexture\s*\(/,'Pilot must not use a second procedural material system');
assert.match(shared,/Spot UV/,'Original SharedStudio finishing UI must remain present');
assert.match(shared,/drawFlat\(\)/,'Original flat artwork rendering must remain present');
assert.match(adapter,/extends SharedStudio/,'Mahabat adapter must subclass the original studio');
assert.match(adapter,/source:'mahabat-engine'/,'Flat sheet source must be Mahabat Engine');
assert.match(productionLink,/MachineEngine\.match/,'Production link must use MachineEngine.match for profile matching');
assert.match(productionLink,/MachineEngine\.evaluate/,'Production link must evaluate the selected machine profile');
assert.match(productionLink,/CostEngine\.estimate/,'Production link must connect CostEngine to nesting/machine/finishing metrics');
assert.match(engineeringPanel,/Production Route Comparison/,'Route comparison must stay inside the engineering panel');
assert.match(nest,/clipper-lib@6\.4\.2/,'Professional nesting must load the Clipper dependency used by Mahaba NestEngine');
assert.match(nest,/engine\.solve\(state\.template,null/,'NFP must be generated by the original NestEngine makeN path');
assert.doesNotMatch(nest,/nfp-lite/,'Production nesting must not use the experimental NFP-lite solver');

const native=generateMahabatNative('EVC11001',{L:125,W:105,H:88,DT:1,MAT:1,FD:2});
assert.equal(native.source,'mahabat-engine');
assert.equal(native.drawings.length,1);
assert.ok(native.materials.outside.values.sheetTexMatrix_Uni,'Artwork mapping matrix is required');
assert.ok(native.materials.inside.values.sheetTexMatrix_Uni,'Inside artwork mapping matrix is required');
assert.ok(native.mahabaGeometry[0].outline.length>=3,'Exact cut outline is required for nesting');
assert.ok(native.mahabaGeometry[0].lines.some(x=>x.type==='cut'));
assert.ok(native.mahabaGeometry[0].lines.some(x=>x.type==='crease'));
assert.ok(native.engineeringModel.metrics.blank_area_mm2>0,'Legacy EVC11001 model must expose cost-ready blank area metrics');
assert.ok(native.engineeringModel.nesting.bounds.width>0,'Legacy EVC11001 model must expose nesting bounds');

console.log(JSON.stringify({ok:true,architecture:'Mahaba Library Studio + Mahabat geometry provider',template:native.code}));
